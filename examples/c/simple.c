// add returns the sum of a and b.
int add(int a, int b) {
    return a + b;
}

/*
 * sub returns the difference of a and b.
 * It uses a multi-line block comment so the
 * doc-extraction has more than one line to join.
 */
int sub(int a, int b) {
    return a - b;
}

int mul(int a, int b) {
    return a * b;
}
